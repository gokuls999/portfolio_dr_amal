/* ── Aurora Canvas ── */
const cv=document.getElementById('aurora'),c=cv.getContext('2d');
let W,H,pts=[];
const resize=()=>{W=cv.width=window.innerWidth;H=cv.height=window.innerHeight;};
resize(); window.addEventListener('resize',resize);

// Create nebula points
for(let i=0;i<6;i++){
  pts.push({
    x:Math.random()*W, y:Math.random()*H,
    vx:(Math.random()-.5)*.3, vy:(Math.random()-.5)*.3,
    r:150+Math.random()*250,
    gold:Math.random()<.5,
    a:Math.random()*.06+.02
  });
}

// Stars
let stars=[];
for(let i=0;i<180;i++) stars.push({x:Math.random()*W,y:Math.random()*H,r:Math.random()*1.1+.2,o:Math.random()*.7+.1,gold:Math.random()<.2,phase:Math.random()*Math.PI*2});

function draw(){
  c.clearRect(0,0,W,H);
  const t=Date.now()*.001;

  // Nebula glows
  pts.forEach(p=>{
    p.x+=p.vx; p.y+=p.vy;
    if(p.x<-p.r||p.x>W+p.r) p.vx*=-1;
    if(p.y<-p.r||p.y>H+p.r) p.vy*=-1;
    const g=c.createRadialGradient(p.x,p.y,0,p.x,p.y,p.r);
    const col=p.gold?`rgba(184,147,58,${p.a})`:`rgba(22,27,44,${p.a*2})`;
    g.addColorStop(0,col);
    g.addColorStop(1,'rgba(0,0,0,0)');
    c.beginPath();c.arc(p.x,p.y,p.r,0,Math.PI*2);
    c.fillStyle=g;c.fill();
  });

  // Stars
  stars.forEach(s=>{
    const pulse=.5+.5*Math.sin(t*s.o+s.phase);
    const o=s.o*.5+pulse*.3;
    c.beginPath();c.arc(s.x,s.y,s.r,0,Math.PI*2);
    c.fillStyle=s.gold?`rgba(212,170,85,${o})`:`rgba(245,240,232,${o})`;
    c.fill();
  });

  requestAnimationFrame(draw);
}
draw();

